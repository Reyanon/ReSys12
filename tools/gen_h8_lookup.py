#!/usr/bin/env python3
# ReSys12: derive h8_lookup.inc from the generated h8_ops.inc (tools/gen_h8.py).
# h8_exec_full() picks the handler of an instruction with three nested switches on h8.inst_state. For the common case
# (inst_state < 0x10000: a fresh instruction whose first word is inst_state) the same switches are turned into
# h8_lookup(st), which returns the handler instead of calling it, so h8.c can fill a 64K-entry table once and dispatch
# with a single indirect call.
#   python3 tools/gen_h8_lookup.py src/h8/h8_ops.inc src/h8/h8_lookup.inc
import re
import sys


def main(argv):
    src = open(argv[1], encoding="utf-8").read()
    start = src.index("static void h8_exec_full(void)")
    body = src[start:]
    body = body.replace("static void h8_exec_full(void)", "static h8_handler h8_lookup(uint32_t st)", 1)
    body = body.replace("h8.inst_state", "st")
    # "name();" -> "return name;" (op_*, dispatch_*, state_*, illegal, h8_unhandled_state)
    body = re.sub(r"\b([A-Za-z_][A-Za-z0-9_]*)\(\);", r"return \1;", body)
    with open(argv[2], "w", newline="\n") as f:
        f.write("// ReSys12: generated by tools/gen_h8_lookup.py from h8_ops.inc. Do not edit.\n")
        f.write("typedef void (*h8_handler)(void);\n\n")
        # every path returns inside the switches; the final return only keeps the compiler quiet
        body = body.rstrip()
        assert body.endswith("}")
        f.write(body[:-1] + "\treturn illegal;\n}\n")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
