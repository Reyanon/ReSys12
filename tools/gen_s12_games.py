#!/usr/bin/env python3
"""Generate src/romload/s12_games.h (System 12 set table) from MAME namcos12.cpp.

Usage: python -I tools/gen_s12_games.py <namcos12.cpp> [out]
Only names, sizes, offsets and CRCs come from MAME (no ROM data).
"""
import re
import sys

REGIONS = {'maincpu:rom': 'S12_RGN_MAIN', 'bankedroms': 'S12_RGN_BANK', 'sub': 'S12_RGN_SUB',
           'c352': 'S12_RGN_C352', 'at28c16': 'S12_RGN_EEPROM', 'm148': 'S12_RGN_M148', 'iocpu': 'S12_RGN_IOCPU'}
LOADS = {'ROM_LOAD': 'S12_LD_PLAIN', 'ROM_LOAD16_BYTE': 'S12_LD_16_BYTE', 'ROM_LOAD16_WORD_SWAP': 'S12_LD_16_WORD_SWAP',
         'ROM_LOAD32_BYTE': 'S12_LD_32_BYTE', 'ROM_LOAD32_WORD': 'S12_LD_32_WORD'}
MACHINES = {'coh700': 'S12_M_COH700', 'coh700b': 'S12_M_COH700B', 'coh716': 'S12_M_COH716', 'aplarail': 'S12_M_APLARAIL',
            'technodr': 'S12_M_TECHNODR', 'cdxa_pcb': 'S12_M_CDXA', 'questff': 'S12_M_QUESTFF', 'golgo13': 'S12_M_GOLGO13',
            'truckk': 'S12_M_TRUCKK', 'kartduel': 'S12_M_KARTDUEL'}
STATES = {'namcos12_state': 'S12_S_BASE', 'namcos12_altbank_state': 'S12_S_ALTBANK', 'namcos12_cdxa_state': 'S12_S_CDXA',
          'tektagt_state': 'S12_S_TEKTAGT', 'ptblank2_state': 'S12_S_PTBLANK2', 'technodr_state': 'S12_S_TECHNODR',
          'golgo13_state': 'S12_S_GOLGO13', 'truckk_state': 'S12_S_TRUCKK', 'kartduel_state': 'S12_S_KARTDUEL'}

GAME_RE = re.compile(
    r'^GAME\(\s*(\d+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*(\w+),\s*\w+,\s*(ROT\d+),'
    r'\s*"([^"]*)",\s*"([^"]*)",\s*([^)]*)\)\s*(?:/\*\s*(KC\d+)\s*\*/)?')
NUM = r'(0x[0-9a-fA-F]+|\d+)'


def num(s):
    return int(s, 0)


# Load offsets MAME has wrong, by (file, CRC): the data is checked against other dumps of the same chips.
# tektagtc1a: its 4MB wave ROMs are the halves of tektagt's 8MB ones (wave0 = l0 + h0, wave1 = l1 + h1); MAME loads
# l0, l1, h0, h1 in that order, which plays wrong samples (the coin sound) from 4MB up
OFFSET_FIX = {
    ('teg2wavel1', 0xf5ab70e6): 0x0800000,
    ('teg2waveh0', 0xbc0325bf): 0x0400000,
}


def parse(path):
    with open(path, encoding='utf-8', errors='replace') as f:
        lines = f.read().splitlines()
    sets = {}
    cur = None
    region = None
    for ln in lines:
        s = ln.strip()
        m = re.match(r'^ROM_START\(\s*(\w+)\s*\)', s)
        if m:
            cur = {'regions': {}, 'roms': []}
            sets[m.group(1)] = cur
            continue
        if cur is None:
            continue
        if s.startswith('ROM_END'):
            cur = None
            continue
        m = re.match(r'^ROM_REGION(?:32_LE)?\(\s*' + NUM + r'\s*,\s*"([^"]+)"', s)
        if m:
            region = m.group(2)
            cur['regions'][region] = num(m.group(1))
            continue
        m = re.match(r'^(ROM_LOAD\w*)\(\s*"([^"]+)"\s*,\s*' + NUM + r'\s*,\s*' + NUM + r'\s*,\s*(.*)$', s)
        if m:
            kind, name, off, size, rest = m.groups()
            crc = re.search(r'CRC\(([0-9a-fA-F]+)\)', rest)
            flags = []
            if 'NO_DUMP' in rest:
                flags.append('S12_F_NODUMP')
            if 'BAD_DUMP' in rest:
                flags.append('S12_F_BADDUMP')
            if region not in REGIONS:  # regions of other boards (e.g. cabinet_io in MAME 0.260): not loaded
                continue
            crcv = int(crc.group(1), 16) if crc else 0
            cur['roms'].append((REGIONS[region], LOADS[kind], OFFSET_FIX.get((name, crcv), num(off)), num(size), crcv,
                                name, '|'.join(flags) or '0'))
            continue
        m = re.match(r'^ROM_RELOAD\(\s*' + NUM + r'\s*,\s*' + NUM, s)
        if m:
            cur['roms'].append((REGIONS[region], 'S12_LD_RELOAD', num(m.group(1)), num(m.group(2)), 0, '', '0'))
            continue
        m = re.match(r'^ROM_FILL\(\s*' + NUM + r'\s*,\s*' + NUM + r'\s*,\s*' + NUM, s)
        if m:
            cur['roms'].append((REGIONS[region], 'S12_LD_FILL', num(m.group(1)), num(m.group(2)), num(m.group(3)), '', '0'))
            continue
    games = []
    for ln in lines:
        m = GAME_RE.match(ln)
        if m:
            games.append(m.groups())
    return sets, games


def cstr(s):
    return '"' + s.replace('\\', '\\\\').replace('"', '\\"') + '"'


def main():
    # --suffix X: arrays s12_roms_X / s12_games_X (an extra table, e.g. from an older MAME whose sets differ)
    args = sys.argv[1:]
    sfx = ''
    if len(args) >= 2 and args[0] == '--suffix':
        sfx = '_' + args[1]
        args = args[2:]
    if len(args) < 1:
        sys.exit('usage: gen_s12_games.py [--suffix X] <namcos12.cpp> [out]')
    sets, games = parse(args[0])
    out = args[1] if len(args) > 1 else 'src/romload/s12_games.h'
    guard = 'S12_GAMES' + sfx.upper() + '_H'
    t = ['// generated by tools/gen_s12_games.py from MAME src/mame/namco/namcos12.cpp (names, sizes, CRCs only). Do not edit.',
         f'#ifndef {guard}', f'#define {guard}', '', '#include "s12_types.h"', '']
    t.append(f'static const S12RomEntry s12_roms{sfx}[] = {{')
    starts = {}
    n = 0
    for g in games:
        name = g[1]
        starts[name] = n
        for r in sets[name]['roms']:
            rgn, ld, off, size, crc, fname, flags = r
            t.append(f'\t{{ {rgn}, {ld}, {flags}, 0x{off:07x}, 0x{size:07x}, 0x{crc:08x}, {cstr(fname)} }}, // {name}')
            n += 1
    t.append('};')
    t.append('')
    t.append(f'static const S12Game s12_games{sfx}[] = {{')
    for g in games:
        year, name, parent, machine, inputs, state, rot, maker, title, flags, kc = g
        rg = sets[name]['regions']
        st = MACHINES.get(machine, 'S12_M_COH700')  # an extra table only supplies ROM lists; metadata comes from the main one
        t.append(f'\t{{ {cstr(name)}, {cstr("" if parent == "0" else parent)}, {cstr(title)}, {cstr(maker)}, {year}, '
                 f'{st}, {STATES.get(state, "S12_S_BASE")}, {cstr(inputs)}, {90 if rot == "ROT90" else 0}, '
                 f'{"S12_G_NOT_WORKING" if "MACHINE_NOT_WORKING" in flags else "0"}, {cstr(kc or "")}, '
                 f'0x{rg.get("maincpu:rom", 0):x}, 0x{rg.get("bankedroms", 0):x}, 0x{rg.get("sub", 0):x}, 0x{rg.get("c352", 0):x}, '
                 f'{starts[name]}, {len(sets[name]["roms"])} }},')
    t.append('};')
    t.append('')
    t.append(f'#define S12_NUM_GAMES{sfx.upper()} ((int)(sizeof(s12_games{sfx}) / sizeof(s12_games{sfx}[0])))')
    t.append('')
    t.append('#endif')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(t) + '\n')
    print(f'{out}: {len(games)} sets, {n} rom entries')


if __name__ == '__main__':
    main()
